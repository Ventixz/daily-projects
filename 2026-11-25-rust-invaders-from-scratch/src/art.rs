#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn all_art_loads_with_expected_sizes() {
        let a = art();
        for frames in [&a.drone, &a.stinger, &a.brute] {
            assert_eq!(frames[0].h, 8);
            assert_eq!(
                frames[0].w, frames[1].w,
                "animation frames must share a width"
            );
            assert_ne!(frames[0], frames[1], "animation frames must differ");
        }
        assert_eq!((a.player.w, a.player.h), (13, 8));
        assert_eq!((a.shield.w, a.shield.h), (22, 16));
        assert_eq!(a.alien_bullet[0].h, a.alien_bullet[1].h);
    }
}
