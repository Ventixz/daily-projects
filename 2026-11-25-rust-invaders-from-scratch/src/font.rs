//! A 5x7 bitmap font. Each glyph is seven rows; each row is five bits with
//! the leftmost pixel in bit 4. Characters advance 6 pixels (1 px gap).

use crate::buffer::Buffer;

pub const GLYPH_W: i32 = 5;
pub const GLYPH_H: i32 = 7;
pub const ADVANCE: i32 = 6;

/// Rows for a character, or `None` if the font has no glyph for it.
pub fn glyph(c: char) -> Option<[u8; 7]> {
    Some(match c.to_ascii_uppercase() {
        '0' => [0x0E, 0x11, 0x13, 0x15, 0x19, 0x11, 0x0E],
        '1' => [0x04, 0x0C, 0x04, 0x04, 0x04, 0x04, 0x0E],
        '2' => [0x0E, 0x11, 0x01, 0x02, 0x04, 0x08, 0x1F],
        '3' => [0x1F, 0x02, 0x04, 0x02, 0x01, 0x11, 0x0E],
        '4' => [0x02, 0x06, 0x0A, 0x12, 0x1F, 0x02, 0x02],
        '5' => [0x1F, 0x10, 0x1E, 0x01, 0x01, 0x11, 0x0E],
        '6' => [0x06, 0x08, 0x10, 0x1E, 0x11, 0x11, 0x0E],
        '7' => [0x1F, 0x01, 0x02, 0x04, 0x08, 0x08, 0x08],
        '8' => [0x0E, 0x11, 0x11, 0x0E, 0x11, 0x11, 0x0E],
        '9' => [0x0E, 0x11, 0x11, 0x0F, 0x01, 0x02, 0x0C],
        'A' => [0x0E, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x11],
        'B' => [0x1E, 0x11, 0x11, 0x1E, 0x11, 0x11, 0x1E],
        'C' => [0x0E, 0x11, 0x10, 0x10, 0x10, 0x11, 0x0E],
        'D' => [0x1C, 0x12, 0x11, 0x11, 0x11, 0x12, 0x1C],
        'E' => [0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x1F],
        'F' => [0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x10],
        'G' => [0x0E, 0x11, 0x10, 0x17, 0x11, 0x11, 0x0F],
        'H' => [0x11, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x11],
        'I' => [0x0E, 0x04, 0x04, 0x04, 0x04, 0x04, 0x0E],
        'J' => [0x07, 0x02, 0x02, 0x02, 0x02, 0x12, 0x0C],
        'K' => [0x11, 0x12, 0x14, 0x18, 0x14, 0x12, 0x11],
        'L' => [0x10, 0x10, 0x10, 0x10, 0x10, 0x10, 0x1F],
        'M' => [0x11, 0x1B, 0x15, 0x15, 0x11, 0x11, 0x11],
        'N' => [0x11, 0x11, 0x19, 0x15, 0x13, 0x11, 0x11],
        'O' => [0x0E, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E],
        'P' => [0x1E, 0x11, 0x11, 0x1E, 0x10, 0x10, 0x10],
        'Q' => [0x0E, 0x11, 0x11, 0x11, 0x15, 0x12, 0x0D],
        'R' => [0x1E, 0x11, 0x11, 0x1E, 0x14, 0x12, 0x11],
        'S' => [0x0F, 0x10, 0x10, 0x0E, 0x01, 0x01, 0x1E],
        'T' => [0x1F, 0x04, 0x04, 0x04, 0x04, 0x04, 0x04],
        'U' => [0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E],
        'V' => [0x11, 0x11, 0x11, 0x11, 0x11, 0x0A, 0x04],
        'W' => [0x11, 0x11, 0x11, 0x15, 0x15, 0x15, 0x0A],
        'X' => [0x11, 0x11, 0x0A, 0x04, 0x0A, 0x11, 0x11],
        'Y' => [0x11, 0x11, 0x11, 0x0A, 0x04, 0x04, 0x04],
        'Z' => [0x1F, 0x01, 0x02, 0x04, 0x08, 0x10, 0x1F],
        ' ' => [0; 7],
        '-' => [0x00, 0x00, 0x00, 0x1F, 0x00, 0x00, 0x00],
        ':' => [0x00, 0x0C, 0x0C, 0x00, 0x0C, 0x0C, 0x00],
        '.' => [0x00, 0x00, 0x00, 0x00, 0x00, 0x0C, 0x0C],
        '!' => [0x04, 0x04, 0x04, 0x04, 0x04, 0x00, 0x04],
        '=' => [0x00, 0x00, 0x1F, 0x00, 0x1F, 0x00, 0x00],
        '<' => [0x02, 0x04, 0x08, 0x10, 0x08, 0x04, 0x02],
        '>' => [0x08, 0x04, 0x02, 0x01, 0x02, 0x04, 0x08],
        '?' => [0x0E, 0x11, 0x01, 0x02, 0x04, 0x00, 0x04],
        '/' => [0x01, 0x01, 0x02, 0x04, 0x08, 0x10, 0x10],
        _ => return None,
    })
}

/// Width in pixels of `text` drawn with [`draw_text`].
pub fn text_width(text: &str) -> i32 {
    let n = text.chars().count() as i32;
    if n == 0 {
        0
    } else {
        n * ADVANCE - 1
    }
}

/// Draws `text` with its top-left at `(x, y)`. Unknown characters draw as `?`.
pub fn draw_text(buf: &mut Buffer, text: &str, x: i32, y: i32, color: u32) {
    let mut cx = x;
    for c in text.chars() {
        let rows = glyph(c).or_else(|| glyph('?')).unwrap();
        for (ry, bits) in rows.iter().enumerate() {
            for rx in 0..GLYPH_W {
                if bits & (0x10 >> rx) != 0 {
                    buf.set(cx + rx, y + ry as i32, color);
                }
            }
        }
        cx += ADVANCE;
    }
}

/// Draws `text` horizontally centred on the buffer.
pub fn draw_centered(buf: &mut Buffer, text: &str, y: i32, color: u32) {
    let x = (buf.w as i32 - text_width(text)) / 2;
    draw_text(buf, text, x, y, color);
}

#[cfg(test)]
mod tests {
    use super::*;

    const CHARSET: &str = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ-:.!=<>?/";

    #[test]
    fn every_glyph_is_distinct_and_fits_five_bits() {
        let glyphs: Vec<[u8; 7]> = CHARSET.chars().map(|c| glyph(c).unwrap()).collect();
        for (i, a) in glyphs.iter().enumerate() {
            assert!(
                a.iter().all(|&r| r < 0x20),
                "glyph {i} uses more than 5 columns"
            );
            for b in &glyphs[i + 1..] {
                assert_ne!(a, b);
            }
        }
        assert_eq!(glyph('a'), glyph('A'));
    }

    #[test]
    fn text_draws_where_expected() {
        let mut b = Buffer::new(20, 8);
        draw_text(&mut b, "1", 0, 0, 9);
        // '1' row 0 is 0x04: only the middle column is lit.
        assert_eq!(b.get(2, 0), Some(9));
        assert_eq!(b.get(0, 0), Some(0));
        assert_eq!(text_width("SCORE"), 29);
        assert_eq!(text_width(""), 0);
    }

    #[test]
    fn unknown_characters_fall_back_to_question_mark() {
        let (mut a, mut b) = (Buffer::new(6, 7), Buffer::new(6, 7));
        draw_text(&mut a, "~", 0, 0, 1);
        draw_text(&mut b, "?", 0, 0, 1);
        assert_eq!(a.px, b.px);
    }
}
